package spacelets;

import java.util.HashSet;
import java.util.Iterator;
import java.util.Random;
import java.util.Set;

/**
 * Generates unique names consisting of 4-digit integers.
 * 
 * @author Rookie
 */
public class IntegerNameGenerator implements NameGenerator {
	/**
	 * When running through an iterator, it will generate this many names
	 */
	private static final int GENERATION_LIMIT = 100;

	/**
	 * When running next(), the max number of times the while loop can execute.
	 */
	private static final int ATTEMPT_LIMIT = 100;
	
	/**
	 * The current name to return when running next().
	 */
	private String currentName;
	/**
	 * A set of names that have been used. Promotes uniqueness.
	 */
	private final Set<String> usedNames;
	/**
	 * Random number generator.
	 */
	private final Random random;
	/**
	 * The number of names that have been generated by this instance.
	 */
	private int valuesGenerated;
	
	/**
	 * Create a new name generator.
	 * 
	 * @param random
	 */
	public IntegerNameGenerator(Random random) {
		currentName = null;
		usedNames = new HashSet<>();
		this.random = random;
		valuesGenerated = 0;
		next();
	}

	/**
	 * Can continue generating if:
	 * - More unique names can be created
	 * - Limit has not been reached
	 */
	@Override
	public boolean hasNext() {
		return currentName != null && valuesGenerated < GENERATION_LIMIT;
	}

	/**
	 * Returns itself.
	 */
	@Override
	public Iterator<String> iterator() {
		return this;
	}

	/**
	 * Returns the next unique name.
	 */
	@Override
	public String next() {
		// Cache old name
		String oldName = currentName;
		
		// Attempt to generate unique name (and check uniqueness)
		int overflow = 0;
		while ((currentName == null || usedNames.contains(currentName)) && overflow < ATTEMPT_LIMIT) {
			currentName = String.valueOf(random.nextInt(1000, 1005));
			overflow++;
		}
		// Set name to null if unique name cannot be generated
		if (overflow >= ATTEMPT_LIMIT) {
			currentName = null;
		} else {
			usedNames.add(currentName);
			valuesGenerated++;
		}
		
		return oldName;
	}
}
